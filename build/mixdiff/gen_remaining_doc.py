"""Writes docs/ASM_REMAINING_mixer.md: the assembled functions of 0x004bdf00-0x004d4100 (Smush audio / video, mixer,
DirectSound glue) before and after the work in build/overrides_mixer*.c, and what is still assembled (nothing).
usage: python -I build/mixdiff/gen_remaining_doc.py [<commit with the old names/asm_funcs.json>]   (default 223e097)"""
import glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OLD = sys.argv[1] if len(sys.argv) > 1 else "223e097"
LO, HI = 0x4bdf00, 0x4d4100
PROG = "GRIMFANDANGO.EXE"

old = json.loads(subprocess.check_output(["git", "show", "%s:names/asm_funcs.json" % OLD], cwd=ROOT))[PROG]
new = json.load(open(os.path.join(ROOT, "names", "asm_funcs.json")))[PROG]
inr = lambda L: sorted(a for a in L if LO <= int(a, 16) <= HI)
old_r, new_r = inr(old), inr(new)
funcs = {f["address"]: f["name"] for f in json.load(open(os.path.join(ROOT, "raw", PROG, "functions.json")))}
src = {}
for p in sorted(glob.glob(os.path.join(ROOT, "build", "overrides_mixer*.c"))):
    t = open(p, encoding="utf-8").read()
    for m in re.finditer(r"(?m)^[A-Za-z_][\w \*]*?\b(\w+)\(", t):
        src.setdefault(m.group(1), os.path.basename(p))
rows = []
for a in old_r:
    n = funcs.get(a, "?")
    rows.append((src.get(n, "?"), a, n, "still assembled" if a in new_r else "C"))
by = {}
for r in rows:
    by.setdefault(r[0], []).append(r)
out = ["# Assembled functions of the Smush / mixer range (0x004bdf00 - 0x004d4100)", "",
       "Generated by `build/mixdiff/gen_remaining_doc.py` (do not edit by hand).  Scope: the DirectSound / software mixer, the Smush",
       "audio and video glue, the Blocky16 frame decoder, AnimPlay, the zlib glue of the save files and the light editor's text field",
       "code.  Notes and test results: `docs/notes/mixer.md`.", "",
       "| | functions assembled |", "|---|---|",
       "| before (names/asm_funcs.json at %s) | %d |" % (OLD, len(old_r)),
       "| after | %d |" % len(new_r), ""]
if new_r:
    out += ["## Still assembled", "", "| address | name |", "|---|---|"] + ["| %s | `%s` |" % (a, funcs.get(a, "?")) for a in new_r] + [""]
else:
    out += ["Nothing in this range is assembled any more: every function is C (written from the machine code and checked against it", "with a differential test, see the notes), so there is no list of reasons.", ""]
out += ["## Converted, by file", ""]
for f in sorted(by):
    out += ["### build/%s (%d)" % (f, len(by[f])), "", "| address | name |", "|---|---|"] + ["| %s | `%s` |" % (a, n) for _, a, n, _ in by[f]] + [""]
open(os.path.join(ROOT, "docs", "ASM_REMAINING_mixer.md"), "w", newline="\n").write("\n".join(out))
print(len(old_r), "->", len(new_r))
