"""Fallback for a module that does not compile: copy it with the body of every
function that has a compiler error replaced by a trap, so the rest of the module
still yields an object file. The original body is kept under `#if 0`.

usage: python -I stubify.py <src.c> <gcc-log> <out.c>   (run by build/Makefile)

Exit status 1 when an error is outside any function (e.g. in a header): stubbing
cannot help then."""
import re
import sys

MARK = re.compile(r"^/\* ---- 0x([0-9a-f]+)\s+(\S+).*---- \*/")


def main(src, log, out):
    lines = open(src, encoding="utf-8", errors="replace").read().split("\n")
    marks = [i for i, l in enumerate(lines) if MARK.match(l)]
    bad_lines = set()
    outside = 0
    base = src.replace("\\", "/").rsplit("/", 1)[-1]
    for l in open(log, encoding="utf-8", errors="replace"):
        m = re.match(r"^(.*?):(\d+):\d+: (?:fatal )?error:", l)
        if not m:
            continue
        if m.group(1).replace("\\", "/").endswith("/" + base) or m.group(1) == base:
            bad_lines.add(int(m.group(2)) - 1)
        else:
            outside += 1
    # errors reported inside a macro expansion point at the header; gcc also prints
    # the use site as "<file>:<line>: note: in expansion of macro", count those
    for l in open(log, encoding="utf-8", errors="replace"):
        m = re.match(r"^(.*?):(\d+):\d+: note: in expansion of macro", l)
        if m and (m.group(1).replace("\\", "/").endswith("/" + base)):
            bad_lines.add(int(m.group(2)) - 1)
    # an error in a header that comes from a macro used in the file is fine; one
    # that is not attributed to any line of this file is not
    if outside and not bad_lines:
        return 1
    bad_funcs = set()
    for b in bad_lines:
        owner = None
        for k in marks:
            if k > b:
                break
            owner = k
        if owner is None:
            return 1
        bad_funcs.add(owner)
    out_lines = list(lines)
    stubbed = []
    for k in sorted(bad_funcs, reverse=True):
        nxt = next((x for x in marks if x > k), len(lines))
        # function body: first "{" at column 0 after the marker, last "}" at column 0
        try:
            ob = next(i for i in range(k, nxt) if lines[i] == "{")
            cb = max(i for i in range(ob, nxt) if lines[i] == "}")
        except (StopIteration, ValueError):
            return 1
        mm = MARK.match(lines[k])
        stubbed.append(mm.group(2))
        out_lines[ob:cb + 1] = (["{", f"  GHIDRA_STUBBED(0x{mm.group(1)}); /* body did not compile, see .log */", "}",
                                 "#if 0 /* original body */"] + lines[ob:cb + 1] + ["#endif"])
    hdr = ["/* GENERATED by build/stubify.py from " + src + ": functions with compile errors",
           " * are replaced by a trap: " + ", ".join(sorted(stubbed)) + " */",
           "#define GHIDRA_STUBBED(addr) __builtin_trap()"]
    # keep #line info so later diagnostics still point at the original file
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(hdr) + "\n" + f'#line 1 "{src}"\n' + "\n".join(out_lines))
    print(f"stubbed {len(stubbed)} function(s) in {base}: {', '.join(sorted(stubbed))}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
