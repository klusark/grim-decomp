/* The iMUSE re-entrancy guard (g_dwWvSlicingHalted, Enter/Leave around nearly every Im* call) is a plain counter:
 * Enter is INC without LOCK, Leave is load / test / dec / store. The WINMM heartbeat thread and the main thread
 * leave at the same moment now and then, both read 2 and store 1, and the counter stays 1 for good: ImHeartbeat
 * (which only runs at 0) never runs again, no stream is consumed and SoundsFloodMusicBuffer (sputRoom_LoadResources)
 * spins forever (seen with fast set switches and with the original binary too). Same semantics, made atomic. */
/* OVERRIDES: ImWaveHalt ImWaveProceed */
__asm__(".text\n"
        ".def _ImWaveHalt; .scl 2; .type 32; .endef\n"
        ".globl _ImWaveHalt\n"
        "_ImWaveHalt:\n"
        "    lock incl _g_dwWvSlicingHalted\n"
        "    ret\n"
        ".def _ImWaveProceed; .scl 2; .type 32; .endef\n"
        ".globl _ImWaveProceed\n"
        "_ImWaveProceed:\n"
        "1:  movl _g_dwWvSlicingHalted, %eax\n"
        "    testl %eax, %eax\n"
        "    jz 2f\n"
        "    leal -1(%eax), %ecx\n"
        "    lock cmpxchgl %ecx, _g_dwWvSlicingHalted\n"
        "    jnz 1b\n"
        "2:  ret\n");

/* ==== GRIM_SIMTIME: iMUSE in game time =========================================================================
 * The scripted runs give every frame a fixed game time (GRIM_SIMTIME ms) and run at ~100x real time, but iMUSE is paced by the
 * hardware: a WINMM timer thread calls ImHeartbeat every 20 ms of real time, and a block of the DirectSound ring is refilled
 * only when the play cursor has left it. A sound that lasts 7 s therefore lasts 7 s of real time = 700 s of game time, and
 * the scripts that wait for the end of a sound (wait_for_sound, the shots of kill_hector) time out. With GRIM_SIMTIME set:
 *   - no timer thread (Timer_Start reports success at once, the timer callback never runs): nothing races with the main thread;
 *   - the play cursor (iMUSE_dsound__3a80) is a counter of bytes that advances by game time (avg bytes/s of the stream format);
 *   - the EXE calls GRIM_ImSimStep(ms) once per frame (GRIM_lua_cmd_poll): the cursor moves and ImHeartbeat runs once per 20 ms
 *     of game time (fades, mixing, retiring of finished tracks), whatever the real time between the calls;
 *   - the two loops that wait for the heartbeat (SoundsFloodMusicBuffer, SoundsFillStreamsWhileMusicCritical) tick it themselves;
 *   - iMUSE's timeGetTime is game time too (GRIM_ImTimeGetTime, through build/cleanroom/cleanroom.c's wrapper): the heartbeat's
 *     own 20 ms check, and the sound cache, which stamps each sound it loads and, when full, drops the stopped one loaded first
 *     (CachePurgeOldestStoppedSound): on the real clock which one that is depended on how fast the machine was.
 * The same as grim_tools' grimlaunch imusetime patch (launcher/patch.c), which the clean room's reference was recorded with.
 * The DirectSound buffer is still written and played (muted), so the rest of iMUSE does not notice. Off without GRIM_SIMTIME,
 * and off with GRIM_IMUSE_REALTIME=1: then only the frames have the fixed time and iMUSE keeps its timer thread and the
 * hardware's pace, as on the original exe with grimlaunch's simtime patch alone. */
extern char *GRIM_getenv(const char *) __asm__("_getenv");
int GRIM_ImSimOn(void)
{
    static int on = -1;
    if (on < 0) {
        const char *e = GRIM_getenv("GRIM_SIMTIME"), *rt = GRIM_getenv("GRIM_IMUSE_REALTIME");
        on = (e != 0 && e[0] >= '1' && e[0] <= '9') && !(rt != 0 && rt[0] == '1');
    }
    return on;
}
