"""Stretch goal: link each program from its objects (run by `make link`).

The decompiled code is not a complete program: Ghidra exports no initialised data
(only names and, for some, a type), Windows/DirectX imports are called through
undecorated, unprototyped declarations, and jumps into other functions are
traps. So this links *for completeness*, not to run:

  src/<prog>/data.c    (compiled by the Makefile like every module) the original's
                       initialised data, generated by tools/datagen.py
  obj/<prog>/link_data.c  a definition for every other symbol in globals.h
                       (zero-filled: import slots, resources, names outside the sections)
  obj/<prog>/stubs.c   a trapping definition for every symbol still undefined
                       after that (imports, thunks, FUN_ with no function, LAB_)
  obj/<prog>/<prog>    the linked PE (i686, -nostdlib, at the original image base)

and reports how many symbols each category needed. The DLLs are linked first,
exporting everything, so GRIMFANDANGO.EXE links against the rebuilt LUA.DLL.

usage: python -I link.py <i686-gcc> <srcdir> <objdir> PROG..."""
import glob
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMAGE_BASE = {"GRIMFANDANGO.EXE": "0x400000"}
ORDER = ["LUA.DLL", "IMUSE.DLL", "CHORE.DLL", "GRIMFANDANGO.EXE"]
# rebuilt DLLs a program links against (their exports replace stubs)
DLL_IMPORTS = {"GRIMFANDANGO.EXE": ["LUA.DLL", "IMUSE.DLL", "CHORE.DLL"],
               "IMUSE.DLL": [], "CHORE.DLL": []}
try:
    STDCALL_NAMES = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "stdcall_names.json")))
except (OSError, ValueError):
    STDCALL_NAMES = {}
WIN32_LIBS = ["-lkernel32", "-luser32", "-lgdi32", "-lwinmm", "-lddraw", "-ldinput", "-ldsound",
              "-ladvapi32", "-lcomdlg32", "-lole32", "-lshell32", "-lcomctl32"]


def run(cmd, env):
    p = subprocess.run(cmd, capture_output=True, text=True, env=env)
    return p.returncode, p.stdout + p.stderr


def data_exports(src):
    """Exported *variables* of the rebuilt DLLs (lua_savehook, lua_callhook ...): src/<DLL>/exports.json
    (tools/datagen.py) marks the exports outside the DLL's .text. The EXE reaches them through its
    import address table, which holds the variable's address."""
    names = set()
    for prog in ("LUA.DLL", "IMUSE.DLL", "CHORE.DLL"):
        for e in json.load(open(os.path.join(src, prog, "exports.json"))):
            if e["variable"]:
                names.add(e["name"])
    return names


def defined_data(nm, obj):
    """The data symbols an object defines (`nm --defined-only`), without the leading underscore."""
    p = subprocess.run([nm, "--defined-only", "-g", obj], capture_output=True, text=True)
    if p.returncode:
        raise SystemExit("link.py: nm %s: %s" % (obj, p.stderr))
    out = set()
    for line in p.stdout.splitlines():
        f = line.split()
        if len(f) == 3 and f[1] in "DBR":
            out.add(f[2][1:])
    return out


DATA_EXPORTS = None


def data_c(src, prog, in_sections=frozenset()):
    """Turn each `extern T name;` of globals.h (and the _exref slots of
    functions.h) into a definition, except the symbols src/<prog>/data.c defines
    (`in_sections`)."""
    lines =['#include "ghidra_types.h"', '#include "globals.h"', '#include "functions.h"', ""]
    names = set()
    decls = []
    for hdr in ("globals.h", "functions.h"):
        for line in open(os.path.join(src, prog, hdr), encoding="utf-8"):
            m = re.match(r"^extern (.*?);", line)
            if m:
                decls.append(m.group(1))
    for d in decls:
        if d.startswith("code ") and "*" not in d:
            continue  # LAB_ code address: stubbed as a function
        if "_exref" in d:
            # import address table slot: point it at the real import
            name = re.search(r"\*\s*([A-Za-z_]\w*_exref)", d).group(1)
            if name not in names:
                names.add(name)
                # bind through an asm-named alias: works whether the import is declared
                # stdcall, cdecl or not at all (some slots are exported variables)
                base = name[:-6]
                global DATA_EXPORTS
                if DATA_EXPORTS is None:
                    DATA_EXPORTS = data_exports(src)
                asm_name = STDCALL_NAMES.get(base, "_" + base)
                if base in DATA_EXPORTS:
                    # an exported variable: the original reads its address out of the
                    # import address table slot. Binding to the import library's symbol
                    # would give the address of its code thunk, so fill the slot's value
                    # from __imp_<name> (the loader's resolved address) before main.
                    lines.append(f'extern char *{base}__imp __asm__("__imp_{asm_name}");')
                    lines.append(f"int (STDCALL *{name})();")
                    lines.append(f"__attribute__((constructor)) static void init_{name}(void) {{ {name} = (int (STDCALL *)()){base}__imp; }}")
                else:
                    lines.append(f'extern char {base}__sym __asm__("{asm_name}");')
                    lines.append(f"int (STDCALL *{name})() = (int (STDCALL *)())&{base}__sym;")
            continue
        name = re.search(r"([A-Za-z_]\w*)\s*((?:\[[^\]]*\])*)$", d).group(1)   # (T name, T name[N], T name[A][B])
        if name in names or name in in_sections:
            continue
        names.add(name)
        if d.endswith("[]"):
            if name.startswith("s_"):
                # a string the data sections do not hold has no bytes here: an export problem
                print(f"{prog}: WARNING: {name} is not defined by data.c (outside the data sections?): 4 zero bytes")
            lines.append(d[:-2] + "[4];")
        else:
            lines.append(d + ";")
    return "\n".join(lines) + "\n", names


def undefined_symbols(log):
    syms = set()
    for m in re.finditer(r"undefined reference to `([^']+)'", log):
        syms.add(m.group(1))
    return syms


def link(cc, src, obj, prog, env):
    d = os.path.join(obj, prog)
    # only objects of modules that still exist in src/ (a regenerated tree can drop some)
    mods = [os.path.basename(c)[:-2] for c in sorted(glob.glob(os.path.join(src, prog, "*.c")))]
    # the decompiled MSVC 6 runtime (crt.c) is left out: the host msvcrt provides
    # malloc/fopen/_stricmp/... and the start-up code (see startup.c)
    objs = [os.path.join(d, m + ".o") for m in mods if m != "crt" and os.path.exists(os.path.join(d, m + ".o"))]
    if not objs:
        print(f"{prog}: no objects (run `make objs` first)")
        return
    generated = list(objs)
    cflags = ["-std=gnu11", "-fpermissive", "-w", "-fno-builtin", "-ffreestanding", "-fno-common", "-include",
              os.path.join(os.path.dirname(os.path.abspath(__file__)), "compat.h"),
              "-I" + os.path.join(src, prog)]
    # the coverage build (make COVERAGE=1): the hand-written files are measured too, and the link takes libgcov
    cov = ["--coverage", "-fprofile-update=atomic", "-g", "-DGRIM_COVERAGE"] if os.environ.get("GRIM_COVERAGE") == "1" else []
    cflags += cov
    # the original's data: src/<prog>/data.c (tools/datagen.py), compiled with the other modules
    here = os.path.dirname(os.path.abspath(__file__))
    data_o = os.path.join(d, "data.o")
    if not os.path.exists(data_o):
        print(f"{prog}: no obj/{prog}/data.o (src/{prog}/data.c missing, or it did not compile)")
        return
    in_sections = defined_data(os.path.join(os.path.dirname(cc), "nm") if os.path.dirname(cc) else "nm", data_o)
    print(f"{prog}: data.c: {len(in_sections)} data symbols")
    # Win32 entry points the import libraries lack (intrinsics) + mingwex hooks
    fence = ["-DGRIM_FENCE"] if os.environ.get("GRIM_FENCE") and not prog.endswith(".DLL") else []  # debug allocator, see win32_shims.c
    rc, out = run([cc] + cflags + fence + ["-c", os.path.join(here, "win32_shims.c"), "-o", os.path.join(d, "win32_shims.o")], env)
    if rc:
        print(f"{prog}: win32_shims.c does not compile:\n{out[:2000]}")
        return
    objs.append(os.path.join(d, "win32_shims.o"))
    text, names = data_c(src, prog, in_sections)
    names |= in_sections
    open(os.path.join(d, "link_data.c"), "w", newline="\n").write(text)
    rc, out = run([cc] + cflags + ["-c", os.path.join(d, "link_data.c"), "-o", os.path.join(d, "link_data.o")], env)
    if rc:
        print(f"{prog}: link_data.c does not compile:\n{out[:3000]}")
        return
    is_dll = prog.endswith(".DLL")
    target = os.path.join(d, prog.lower())
    # linked against the host mingw/msvcrt runtime: it supplies the CRT functions the
    # decompiled code calls and the start-up (DllMainCRTStartup / WinMainCRTStartup)
    ldflags = ["-Wl,--enable-stdcall-fixup", "-Wl,--no-insert-timestamp", "-Wl,--allow-multiple-definition",
               "-Wl,--disable-dynamicbase"] + cov[:1]
    if prog in IMAGE_BASE:
        ldflags.append("-Wl,--image-base=" + IMAGE_BASE[prog])
    if is_dll and cov:
        # (a coverage DLL exports grim_cov_dump, its libgcov's __gcov_dump: the exe calls it at exit, startup.c)
        cov_src = os.path.join(d, "cov_export.c")
        open(cov_src, "w", newline="\n").write("/* GENERATED by build/link.py (coverage build) */\nextern void __gcov_dump(void);\n"
                                                 "void grim_cov_dump(void) { __gcov_dump(); }\n")
        rc, out = run([cc, "-m32", "-c", cov_src, "-o", os.path.join(d, "cov_export.o")], env)
        if rc:
            print(f"{prog}: cov_export.c does not compile:\n{out[:2000]}")
            return
        objs.append(os.path.join(d, "cov_export.o"))
    if is_dll:
        # (a coverage DLL keeps its libgcov to itself: exported, the exe would take __gcov_init from it and not its own)
        ldflags += ["-shared", "-Wl,--export-all-symbols"] + (["-Wl,--exclude-libs,libgcov.a"] if cov else []) + [
                    "-Wl,--out-implib=" + os.path.join(d, "lib" + prog.split(".")[0].lower() + ".a")]
    else:
        ldflags += ["-mwindows"]
        rc, out = run([cc] + cflags + ["-c", os.path.join(here, "startup.c"), "-o", os.path.join(d, "startup.o")], env)
        if rc:
            print(f"{prog}: startup.c does not compile:\n{out[:2000]}")
            return
        objs.append(os.path.join(d, "startup.o"))
    # hand-written replacements (see overrides.c); compiled per program for its headers
    ov_flags = {"GRIMFANDANGO.EXE": ["-DGRIM_EXE"], "IMUSE.DLL": ["-DGRIM_IMUSE"], "CHORE.DLL": ["-DGRIM_CHORE"], "LUA.DLL": ["-DGRIM_LUA"]}.get(prog, [])  # per-program sections of overrides.c
    rc, out = run([cc] + cflags + ov_flags + ["-c", os.path.join(here, "overrides.c"), "-o", os.path.join(d, "overrides.o")], env)
    if rc:
        print(f"{prog}: overrides.c does not compile:\n{out[:2000]}")
        return
    objs.append(os.path.join(d, "overrides.o"))
    # readable C that replaces assembled/uncompilable functions (overrides_<topic>.c: overrides_exe.c, then one file per work
    # stream so that parallel work does not touch the same file). Each file is compiled for every program and guards its
    # code with #ifdef GRIM_EXE / GRIM_IMUSE / GRIM_LUA / GRIM_CHORE.
    for ov2 in sorted(glob.glob(os.path.join(here, "overrides_*.c"))):
        stem = os.path.splitext(os.path.basename(ov2))[0]
        rc, out = run([cc] + cflags + ov_flags + ["-c", ov2, "-o", os.path.join(d, stem + ".o")], env)
        if rc:
            print(f"{prog}: {stem}.c does not compile:\n{out[:3000]}")
            return
        objs.append(os.path.join(d, stem + ".o"))
    # test patches for grim_tools/cleanroom (cleanroom/README.md): each file is compiled like an overrides_*.c file, and its
    # `/* WRAPS: a b */` lines become ld --wrap options for the exe (calls of a go to __wrap_a, __real_a is the decompiled a)
    for cr in sorted(glob.glob(os.path.join(here, "cleanroom", "*.c"))):
        stem = "cleanroom_" + os.path.splitext(os.path.basename(cr))[0]
        rc, out = run([cc] + cflags + ov_flags + ["-c", cr, "-o", os.path.join(d, stem + ".o")], env)
        if rc:
            print(f"{prog}: cleanroom/{os.path.basename(cr)} does not compile:\n{out[:3000]}")
            return
        objs.append(os.path.join(d, stem + ".o"))
        # (`/* WRAPS(IMUSE.DLL): a b */` wraps in that program instead)
        for m in re.finditer(r"^/\* WRAPS(?:\(([\w.]+)\))?: ([^*]*?)\s*\*/", open(cr, encoding="utf-8").read(), re.M):
            if (m.group(1) or "GRIMFANDANGO.EXE") == prog:
                ldflags += ["-Wl,--wrap=" + w for w in m.group(2).split()]
    # hand-written fast paths (fastpaths.c): optimised, SSE2
    rc, out = run([cc] + cflags + ov_flags + ["-O2", "-msse2", "-c", os.path.join(here, "fastpaths.c"), "-o", os.path.join(d, "fastpaths.o")], env)
    if rc:
        print(f"{prog}: fastpaths.c does not compile:\n{out[:2000]}")
        return
    objs.append(os.path.join(d, "fastpaths.o"))
    # functions reassembled from the disassembly (tools/gen_asm.py)
    asm_src = os.path.join(src, prog, "asm_funcs.s")
    if os.path.exists(asm_src) and prog == "GRIMFANDANGO.EXE" and not os.environ.get("GRIM_NO_PEEPHOLE"):
        # x87 control-word switching around every float->int conversion -> SSE4.1 (see peephole.py)
        fast_src = os.path.join(d, "asm_funcs_fast.s")
        pr = subprocess.run([sys.executable, "-I", os.path.join(here, "peephole.py"), asm_src, fast_src],
                            capture_output=True, text=True, env=env)
        print(f"{prog}: {pr.stdout.strip()}{pr.stderr.strip()}")
        if pr.returncode == 0:
            asm_src = fast_src
    if os.path.exists(asm_src):
        rc, out = run([cc, "-m32", "-c", asm_src, "-o", os.path.join(d, "asm_funcs.o")], env)
        if rc:
            print(f"{prog}: asm_funcs.s does not assemble:\n{out[:2000]}")
            return
        objs.append(os.path.join(d, "asm_funcs.o"))
    # names/lib_replace.json "aliases": {prog: {C symbol: system library symbol}}: a function of the original
    # runtime that the system library provides under another name (unnamed FUN_ addresses, x87 helpers): a one-jump thunk
    try:
        aliases = json.load(open(os.path.join(ROOT, "names", "lib_replace.json"))).get("aliases", {}).get(prog, {})
    except (OSError, ValueError):
        aliases = {}
    if aliases:
        lines = ["# GENERATED by build/link.py from names/lib_replace.json: original runtime functions served by the system library",
                 "\t.text"]
        for sym, host in sorted(aliases.items()):
            lines += ["\t.globl %s" % sym, "%s:\tjmp *__imp_%s" % (sym, host)]   # via the import table: never to a symbol of this link
        open(os.path.join(d, "lib_alias.s"), "w", newline="\n").write("\n".join(lines) + "\n")
        rc, out = run([cc, "-m32", "-c", os.path.join(d, "lib_alias.s"), "-o", os.path.join(d, "lib_alias.o")], env)
        if rc:
            print(f"{prog}: lib_alias.s does not assemble:\n{out[:2000]}")
            return
        objs.append(os.path.join(d, "lib_alias.o"))
    # a hand-written function must replace its decompiled twin, not sit next to it: --allow-multiple-definition would
    # silently keep whichever object comes first (build_src leaves the twin compiled when it does not recognise the
    # override's definition, e.g. a comment between `)` and `{`)
    nm = os.path.join(os.path.dirname(cc), "nm") if os.path.dirname(cc) else "nm"
    hand = [o for o in objs if os.path.basename(o).startswith(("overrides", "cleanroom_"))]
    def text_syms(files):
        r = subprocess.run([nm, "-g", "--defined-only"] + files, capture_output=True, text=True, env=env)
        return {l.split()[2] for l in r.stdout.splitlines() if len(l.split()) == 3 and l.split()[1] == "T"}
    twice = sorted(text_syms(hand) & text_syms(generated))
    if twice:
        print(f"{prog}: link FAILED: defined both by a hand-written override and by the generated code (build_src did not "
              f"put the twin under #if 0): {' '.join(twice[:20])}")
        return
    libs = []
    for dep in DLL_IMPORTS.get(prog, []):
        imp = os.path.join(obj, dep, "lib" + dep.split(".")[0].lower() + ".a")
        if os.path.exists(imp):
            libs.append(imp)
    libs += ["-lmingwex", "-lgcc"]  # x87 math helpers (sinl, exp2l, ldexpl, sqrtl), 64-bit division
    if prog == "GRIMFANDANGO.EXE" and not os.environ.get("GRIM_BUNDLED_ZLIB"):
        # the system zlib (mingw-w64-i686-zlib) replaces the game's bundled zlib 1.1.3 (names/lib_replace.json "zlib");
        # statically, so the exe needs no zlib DLL
        libs += ["-Wl,-Bstatic", "-lz", "-Wl,-Bdynamic"]
    # the real Win32 / DirectX import libraries (mingw-w64-i686); --enable-stdcall-fixup
    # binds the undecorated `_CreateFileA` of the decompiled code to `_CreateFileA@28`
    libs += WIN32_LIBS
    # (no HMI libraries: overrides_hmifx.c is the HMI effects library IMUSE.DLL imported from HMIFXLIB.DLL)
    stub_path = os.path.join(d, "stubs.c")
    open(stub_path, "w").write("int mainCRTStartup_stub(void) { __builtin_trap(); }\n")
    stubs = set()
    for attempt in range(4):
        rc, out = run([cc] + cflags + ["-c", stub_path, "-o", os.path.join(d, "stubs.o")], env)
        if rc:
            print(f"{prog}: stubs.c does not compile:\n{out[:2000]}")
            return
        rc, out = run([cc, "-m32"] + ldflags + ["-o", target] + objs
                      + [os.path.join(d, "link_data.o"), os.path.join(d, "stubs.o")] + libs, env)
        missing = undefined_symbols(out)
        if rc == 0 or not missing:
            break
        new = missing - stubs
        if not new:
            break
        stubs |= new
        body = ["/* GENERATED by build/link.py: symbols the decompiled code references but",
                " * nothing defines (imports, thunks, FUN_/LAB_ addresses without a function). */",
                "int mainCRTStartup_stub(void) { __builtin_trap(); }"]
        for s in sorted(stubs):
            # ld reports C-level names (the i386 '_' prefix stripped); decorated
            # stdcall (`f@8`) / fastcall (`@f@8`) names need an explicit asm label
            if "@" in s:
                asm = s if s.startswith("@") else "_" + s
                c = "stub_" + re.sub(r"\W", "_", s)
                body.append(f'int {c}(void) __asm__("{asm}");')
                body.append(f"int {c}(void) {{ __builtin_trap(); }}")
            else:
                body.append(f"int {s}() {{ __builtin_trap(); }}")
        open(stub_path, "w", newline="\n").write("\n".join(body) + "\n")
    with open(os.path.join(d, "link.log"), "w") as f:
        f.write(out)
    errors = [l for l in out.splitlines() if "error" in l.lower() or "multiple definition" in l]
    try:
        # src/<prog>/imports.h: `/* <address> */ extern int <name>();`
        imports = set(re.findall(r"extern \w+ (\w+)\(", open(os.path.join(src, prog, "imports.h"), encoding="utf-8").read()))
    except OSError:
        imports = set()
    kinds = {}
    for s in stubs:
        c = s.split("@")[0]
        k = ("FUN_" if c.startswith("FUN_") else "LAB_" if c.startswith("LAB_") else
             "import" if c in imports else "entry" if c == "mainCRTStartup_stub" else "other")
        kinds[k] = kinds.get(k, 0) + 1
    with open(os.path.join(d, "stubs.txt"), "w") as f:
        f.write("\n".join(sorted(stubs)) + "\n")
    status = "LINKED" if rc == 0 else "link FAILED"
    print(f"{prog}: {status} -> {os.path.relpath(target)}; {len(objs)} objects, "
          f"{len(names)} data symbols defined, {len(stubs)} symbols stubbed {kinds}")
    if rc:
        for l in errors[:15]:
            print("   ", l)
        print(f"    (full log: {os.path.relpath(os.path.join(d, 'link.log'))})")
    return rc == 0


def main(cc, src, obj, progs):
    env = dict(os.environ)
    ccdir = os.path.dirname(cc)
    if ccdir:  # the i686 gcc needs its own bin/ first on PATH (cc1, as, ld)
        env["PATH"] = ccdir + os.pathsep + env.get("PATH", "")
    if not os.path.exists(cc) and not os.path.exists(cc + ".exe"):
        print(f"no i686 toolchain at {cc}: install mingw-w64-i686-gcc (pacman -S mingw-w64-i686-gcc)")
        return 1
    # link() returns True only when the program linked; an early return (a file that does not compile) gives None and
    # leaves the previous binary in place, so the whole run fails then instead of silently keeping the old program
    failed = [prog for prog in [p for p in ORDER if p in progs] if not link(cc, src, obj, prog, env)]
    if failed:
        print("link.py: NOT linked: " + ", ".join(failed))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]))
