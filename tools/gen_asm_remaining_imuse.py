"""docs/ASM_REMAINING_imuse.md: the IMUSE.DLL functions that are still assembled, with the reason (agent N).

Reasons are hand-written in names/imuse_asm_reasons.json {address: text}; the list itself is names/asm_funcs.json['IMUSE.DLL']
(written by tools/gen_asm.py --select).  The counts before/after come from names/imuse_asm_reasons.json['_before']."""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
reasons = json.load(open(os.path.join(ROOT, "names", "imuse_asm_reasons.json")))
before = reasons.pop("_before", 243)
done = reasons.pop("_done", None)
names = {f["address"]: f["name"] for f in json.load(open(os.path.join(ROOT, "raw", "IMUSE.DLL", "functions.json")))}
module = {}
for p in glob.glob(os.path.join(ROOT, "src", "IMUSE.DLL", "*.c")):
    for a in re.findall(r"(?m)^/\* ---- 0x([0-9a-f]+)  ", open(p, encoding="utf-8", errors="replace").read()):
        module[a] = os.path.basename(p)
asm = sorted(json.load(open(os.path.join(ROOT, "names", "asm_funcs.json")))["IMUSE.DLL"])
out = ["# IMUSE.DLL functions that are still assembled (agent N)", "",
       "`names/asm_funcs.json` is the selection (`tools/gen_asm.py`); `names/asm_exclude_imuse.json` lists what was moved back to C, "
       "`build/overrides_imuse.c` holds the hand-written C versions.  Generated by `tools/gen_asm_remaining_imuse.py` from "
       "`names/imuse_asm_reasons.json`.", "",
       "| | functions |", "|---|---|", "| assembled before | %d |" % before, "| assembled now | %d |" % len(asm), "",
       "| address | name | module | reason |", "|---|---|---|---|"]
if not asm and done:                     # nothing left: the note of names/imuse_asm_reasons.json['_done'] instead of the table
    out[-2:] = [done]
for a in asm:
    out.append("| %s | `%s` | %s | %s |" % (a, names.get(a, "?"), module.get(a, "?"), reasons.get(a, "NO REASON RECORDED")))
open(os.path.join(ROOT, "docs", "ASM_REMAINING_imuse.md"), "w", newline="\n").write("\n".join(out) + "\n")
print("%d assembled, %d without a reason" % (len(asm), sum(1 for a in asm if a not in reasons)))
