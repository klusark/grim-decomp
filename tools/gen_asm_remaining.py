"""Write docs/ASM_REMAINING.md: every function of GRIMFANDANGO.EXE (0x401000-0x49ffff) that is still rebuilt from
Ghidra's disassembly instead of compiled C, with the reason.

The reason comes from names/asm_reasons.json ({address: "text"}, hand-written, takes precedence) and otherwise from the
audit flags of tools/asm_audit.py (raw/<prog>/audit.json) and the module the function lives in.
Usage: python -I tools/gen_asm_remaining.py   (needs raw/, src/, names/asm_funcs.json up to date)
"""
import glob, json, os, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROG = "GRIMFANDANGO.EXE"
LO, HI = 0x401000, 0x4a0000

FLAG_TEXT = {
    "ftol": "x87 value converted with _ftol: the decompiler loses the operand",
    "x87state": "x87 stack / status word crosses instructions or calls",
    "regs": "register values cross calls or the function boundary (unaff_/extraout_)",
    "carry": "multi-word arithmetic / flags (CARRY, SBORROW)",
    "paramaddr": "parameter slot reused as a local (&param_N)",
    "stackvar": "stack parameters the prototype does not declare (varargs / by-value structs)",
    "jumptable": "computed jump Ghidra could not recover",
    "floatslot": "float stored through an integer slot",
}
MODULE_TEXT = {
    "rdraster.c": "software rasteriser: span / edge-setup inner loops kept as the original machine code (speed, bit-exact pixels)",
    "std3d.c": "Direct3D COM vtable calls (arguments lost by the decompiler)",
    "stddisplay.c": "DirectDraw COM vtable calls (arguments lost by the decompiler)",
    "stdinput.c": "DirectInput COM vtable calls",
}


def main():
    sel = set(json.load(open(os.path.join(ROOT, "names", "asm_funcs.json")))[PROG])
    funcs = {f["address"]: f for f in json.load(open(os.path.join(ROOT, "raw", PROG, "functions.json")))}
    audit = json.load(open(os.path.join(ROOT, "raw", PROG, "audit.json")))
    rp = os.path.join(ROOT, "names", "asm_reasons.json")
    reasons = json.load(open(rp)) if os.path.exists(rp) else {}
    mod = {}
    for sp in glob.glob(os.path.join(ROOT, "src", PROG, "*.c")):
        for a, n in re.findall(r"(?m)^/\* ---- 0x([0-9a-f]+)  (\S+) ---- \*/", open(sp, encoding="utf-8", errors="replace").read()):
            mod[a] = os.path.basename(sp)
    rows = []
    for a in sorted(sel):
        if not LO <= int(a, 16) < HI:
            continue
        name = funcs[a]["name"]
        if a in reasons:
            why = reasons[a]
        else:
            fl = [f for f in audit.get(a, []) if f in FLAG_TEXT]
            why = "; ".join(FLAG_TEXT[f] for f in fl)
            if not why:
                why = MODULE_TEXT.get(mod.get(a), "")
            if not why:
                why = "not converted yet (no known blocker)"
        rows.append((mod.get(a, "?"), a, name, why))
    by = collections.defaultdict(list)
    for r in rows:
        by[r[0]].append(r)
    out = ["# EXE functions still rebuilt from assembly (0x401000-0x49ffff)", "",
           "Generated by `tools/gen_asm_remaining.py` (do not edit by hand; reasons that are not derived from the audit",
           "live in `names/asm_reasons.json`).  A function listed here is compiled from Ghidra's disassembly",
           "(`src/GRIMFANDANGO.EXE/asm_funcs.s`), its C text in `src/` is only for reading.", "",
           "%d functions in %d modules." % (len(rows), len(by)), ""]
    for m in sorted(by, key=lambda m: -len(by[m])):
        if m == "rdraster.c":   # the whole software rasteriser stays machine code: one paragraph instead of 372 rows
            lo, hi = by[m][0][1], by[m][-1][1]
            out += ["## rdraster.c (%d)" % len(by[m]), "",
                    "The RDroid software rasteriser (0x%s-0x%s): polygon set-up (`rdRaster_SetupPoly*`, `EdgeSetup*`, `Grad*`), the per-format "
                    "span fillers (`Span8/16/R/P_*`: flat / textured / lit / z-buffered / colour-keyed variants, about 220 of them) and the "
                    "`Draw*` drivers that walk the edges.  This is float -> fixed-point code with x87 control-word switches (floor/ceil via "
                    "FLDCW, see `build/peephole.py`) and it is the hot loop of the frame (build/BUILD_NOTES.md, Performance: 40-50 percent of a "
                    "frame is the span fillers), so it stays machine code unless a pixel-exact, equally fast C port is written.  "
                    "`python -I tools/asm_audit.py` lists the blocking flag of each function." % (lo, hi), ""]
            continue
        out += ["## %s (%d)" % (m, len(by[m])), "", "| address | name | reason |", "|---|---|---|"]
        out += ["| 0x%s | `%s` | %s |" % (a, n, w) for _, a, n, w in by[m]]
        out.append("")
    open(os.path.join(ROOT, "docs", "ASM_REMAINING.md"), "w", newline="\n").write("\n".join(out))
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
