"""List the Lua functions the engine registers (tables of {char *luaName, code *cfunction} pairs in the
EXE's .rdata/.data), with the C function each one maps to.

Needs raw/GRIMFANDANGO.EXE/sections/*.bin + sections.json + functions.json (python -I tools/export_raw.py).
Usage: python -I tools/list_lua_api.py [--md]      (--md writes docs/LUA_API.md)"""
import json, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "raw", "GRIMFANDANGO.EXE")
funcs = {int(f["address"], 16): f["name"] for f in json.load(open(os.path.join(RAW, "functions.json")))}
mem = {}
for s in json.load(open(os.path.join(RAW, "sections.json"))):
    mem[int(s["start"], 16)] = open(os.path.join(RAW, "sections", s["file"]), "rb").read()
TEXT = (0x401000, 0x4D6200)


def cstr(a):
    for lo, b in mem.items():
        if lo <= a < lo + len(b):
            end = b.find(b"\0", a - lo)
            if end < 0 or end - (a - lo) > 64:
                return None
            s = b[a - lo:end]
            if not s or not all(32 <= c < 127 for c in s):
                return None
            return s.decode()
    return None


tables = []
for lo, b in mem.items():
    i = 0
    while i + 8 <= len(b):
        p, f = struct.unpack_from("<II", b, i)
        if TEXT[0] <= f < TEXT[1] and cstr(p):
            start, entries = i, []
            while i + 8 <= len(b):
                p, f = struct.unpack_from("<II", b, i)
                s = cstr(p)
                if not (s and TEXT[0] <= f < TEXT[1]):
                    break
                entries.append((s, f))
                i += 8
            # real Lua tables map to Lua_* handlers; this skips locale-name tables and the module-init table
            if len(entries) >= 2 and sum(funcs.get(f, "").startswith("Lua_") for _, f in entries) * 2 > len(entries):
                tables.append((lo + start, entries))
            continue
        i += 4

md = "--md" in sys.argv
out = []
if md:
    out.append("# Lua API registered by the engine\n")
    out.append("Generated by `python -I tools/list_lua_api.py --md` from the pointer tables in the EXE's data sections.\n"
               "Each table is passed to `sputLua_RegisterFunctions` (= `lua_openlib`); the left column is the global Lua name, the right the C\n"
               "function (in `src/GRIMFANDANGO.EXE`) that runs when a script calls it. Arguments are read with `lua_lua2C(n)`,\n"
               "`lua_getnumber`, `lua_getstring`; results are pushed with `lua_pushnumber` etc.\n")
for addr, entries in tables:
    if md:
        out.append(f"\n## table at 0x{addr:08x} ({len(entries)} functions)\n\n| Lua name | C function | address |\n|---|---|---|")
        for s, f in entries:
            out.append(f"| `{s}` | `{funcs.get(f, '?')}` | 0x{f:08x} |")
    else:
        out.append(f"== table at {addr:08x}: {len(entries)} entries")
        for s, f in entries:
            out.append(f"   {f:08x} {funcs.get(f, '(not a function)'):40s} {s}")
text = "\n".join(out) + "\n"
if md:
    open(os.path.join(ROOT, "docs", "LUA_API.md"), "w", newline="\n").write(text)
    print("wrote docs/LUA_API.md,", sum(len(e) for _, e in tables), "functions in", len(tables), "tables")
else:
    sys.stdout.write(text)
