"""Write docs/ASM_REMAINING_logic.md: the assembled functions in agent P's scope (GRIMFANDANGO.EXE < 0x4bf000 without the
software rasteriser 0x40ea50-0x4710e0, CHORE.DLL, LUA.DLL) with the reason, from names/asm_reasons_logic.json.
Usage: python -I tools/gen_asm_remaining_logic.py   (needs names/asm_funcs.json and raw/<prog>/functions.json)"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def in_scope(prog, a):
    v = int(a, 16)
    if prog == "GRIMFANDANGO.EXE":
        return v < 0x4bf000 and not 0x40ea50 <= v <= 0x4710e0
    return True


def main():
    sel = json.load(open(os.path.join(ROOT, "names", "asm_funcs.json")))
    rs = json.load(open(os.path.join(ROOT, "names", "asm_reasons_logic.json")))
    before = rs["_before"]
    rows = {}
    for prog in ("GRIMFANDANGO.EXE", "CHORE.DLL", "LUA.DLL"):
        names = {f["address"]: f["name"] for f in json.load(open(os.path.join(ROOT, "raw", prog, "functions.json")))}
        rows[prog] = [(a, names.get(a, "?"), rs.get(prog, {}).get(a, "no reason recorded"))
                      for a in sorted(sel[prog]) if in_scope(prog, a)]
    exe_lo = sum(1 for a, _, _ in rows["GRIMFANDANGO.EXE"] if int(a, 16) < 0x4a0000)
    exe_hi = len(rows["GRIMFANDANGO.EXE"]) - exe_lo
    out = ["# Assembled functions that remain in the game-logic pass (agent P)", "",
           "Scope: GRIMFANDANGO.EXE below 0x004bf000 without the software rasteriser (0x0040ea50-0x004710e0 inclusive of the last span function, which stays assembled),",
           "CHORE.DLL and LUA.DLL.  `names/asm_funcs.json` is the selection; reasons are in `names/asm_reasons_logic.json`.",
           "Generated by `tools/gen_asm_remaining_logic.py`; the notes are in `docs/notes/logic.md`.", "",
           "| range | assembled before | assembled now |", "|---|---|---|",
           "| EXE < 0x4a0000 (without rasteriser) | %d | %d |" % (before["EXE < 0x4a0000 (without rasteriser)"], exe_lo),
           "| EXE 0x4a0000-0x4bf000 | %d | %d |" % (before["EXE 0x4a0000-0x4bf000"], exe_hi),
           "| CHORE.DLL | %d | %d |" % (before["CHORE.DLL"], len(rows["CHORE.DLL"])),
           "| LUA.DLL | %d | %d |" % (before["LUA.DLL"], len(rows["LUA.DLL"])), ""]
    for prog in rows:
        out += ["## " + prog, "", "| address | name | reason |", "|---|---|---|"]
        out += ["| %s | `%s` | %s |" % r for r in rows[prog]]
        out.append("")
    open(os.path.join(ROOT, "docs", "ASM_REMAINING_logic.md"), "w", newline="\n").write("\n".join(out))
    print("%d functions listed" % sum(len(v) for v in rows.values()))


main()
